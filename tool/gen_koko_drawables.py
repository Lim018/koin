# Generates Android vector drawables for Koko from lib/ui/koko_sprite.dart.
# Usage: python3 tool/gen_koko_drawables.py lib/ui/koko_sprite.dart android/app/src/main/res/drawable
import re, sys, os
src = open(sys.argv[1]).read()
out = sys.argv[2]
def rects(name):
    m = re.search(r'%s\s*=\s*(?:<_Px>)?\[(.*?)\];' % re.escape(name), src, re.S)
    return [tuple(float(v) for v in t) for t in re.findall(r'\(([-\d.]+),\s*([-\d.]+),\s*([-\d.]+),\s*([-\d.]+)\)', m.group(1))]
faces_block = re.search(r'_faces = \{(.*?)\n\};', src, re.S).group(1)
faces = {}
for mood, body in re.findall(r'KokoMood\.(\w+): \[(.*?)\]', faces_block, re.S):
    faces[mood] = [tuple(float(v) for v in t) for t in re.findall(r'\(([-\d.]+),\s*([-\d.]+),\s*([-\d.]+),\s*([-\d.]+)\)', body)]
def path(px):
    return ' '.join(f'M{x+1:g},{y+4:g}h{w:g}v{h:g}h{-w:g}z' for x, y, w, h in px)
body, outline, cheeks, anger = rects('_body'), rects('_outline'), rects('_cheeks'), rects('_angerMark')
for mood in ('happy', 'neutral', 'grumpy'):
    grumpy = mood == 'grumpy'
    layers = [('#F7C59F', body), ('#4A3628', outline + faces[mood]),
              ('#E8875A' if grumpy else '#F2A98A', cheeks + (anger if grumpy else []))]
    xml = ['<?xml version="1.0" encoding="utf-8"?>',
           '<!-- Generated by tool/gen_koko_drawables.py from lib/ui/koko_sprite.dart. -->',
           '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
           '    android:width="80dp" android:height="72dp"',
           '    android:viewportWidth="20" android:viewportHeight="18">']
    for color, px in layers:
        xml.append(f'    <path android:fillColor="{color}" android:pathData="{path(px)}"/>')
    xml.append('</vector>')
    open(os.path.join(out, f'koko_{mood}.xml'), 'w').write('\n'.join(xml) + '\n')
    print(mood, len(faces[mood]))
